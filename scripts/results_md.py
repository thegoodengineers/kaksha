"""Write docs/RESULTS.md from results/*.csv so the write-up can't drift from the numbers."""
import pathlib

import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parent.parent
R = ROOT / "results"


def md(df: pd.DataFrame) -> str:
    return df.to_markdown(index=False, floatfmt=".3f")


m = pd.read_csv(R / "metrics.csv")
cols = ["protocol", "method", "L", "mse_hr", "f2", "missed_high_risk", "recall_high_risk",
        "unnecessary_manoeuvres", "false_alarm_rate"]
out = ["# Results (generated by `scripts/results_md.py` from `results/*.csv`; do not edit by hand)", "",
       "All rows: ESA's 2,167 held-out test events, 150 of them high risk (final log10 Pc >= -6). "
       "Only messages received 2+ days before closest approach are used. L = MSE on high-risk events / F2 "
       "(lower is better), the competition's own score.", "",
       "- **official**: fit and tuned on ESA's train events only, as in the original competition.",
       "- **shifted**: 5 folds over the test events; each fold is predicted by a model fitted on ESA's train events "
       "plus the other 4 folds, so no event is ever scored by a model that saw it.", "",
       "## Scores", "", md(m[cols]), "",
       "`rules: clean` and `correction: clean-correction` are the official results we count: each chosen only by train "
       "5-fold CV (`results/cv_selection.csv`, `results/cv_selection_correction.csv`). Neither beats the baseline. "
       "`rules: rules` and `rules: rules+gbm_promote` were chosen after about 60 unlogged exploratory test scorings and "
       "are not counted.", "",
       "## Official split: paired bootstrap of L(clean rule pick) - L(latest-risk rule)", "",
       md(pd.read_csv(R / "official_bootstrap.csv")), "",
       "## Every official-test evaluation we ran (`results/test_log.csv`)", "",
       md(pd.read_csv(R / "test_log.csv").fillna("")), "",
       "## Clean selection: train-only 5-fold CV, top 10 of `results/cv_selection.csv`", "",
       md(pd.read_csv(R / "cv_selection.csv").head(10).fillna("")), "",
       "## Clean selection 2: shrunk correction, top 10 of `results/cv_selection_correction.csv`", "",
       md(pd.read_csv(R / "cv_selection_correction.csv").head(10).fillna("")), "",
       "## Why two protocols: ESA's train and test events behave differently", "",
       md(pd.read_csv(R / "data_summary.csv")), "",
       "`latest_high_final_low`: events whose latest message (2+ days out) said high risk but which ended low.", "",
       "## Calibration (shifted protocol)", "", md(pd.read_csv(R / "calibration.csv")), "",
       "## Uncertainty (shifted protocol)", "", md(pd.read_csv(R / "uncertainty.csv")), "",
       "## Trade-off: missed events against unnecessary manoeuvres (shifted protocol)", "",
       md(pd.read_csv(R / "tradeoff.csv").iloc[::5]), ""]
(ROOT / "docs" / "RESULTS.md").write_text("\n".join(out), encoding="utf-8")
print("wrote docs/RESULTS.md")
